#[derive(Debug, Clone, PartialEq)]
pub enum TokenKind {
    Eof,
    Newline,
    Indent,
    Dedent,

    Identifier(String),
    Int(String),
    Float(String),
    Str(String),

    Fn,
    If,
    Elif,
    Else,
    While,
    For,
    Return,
    Priv,
    True,
    False,
    And,
    Or,
    Not,
    Import,
    As,
    Break,
    Continue,
    Pass,
    In,
    Try,
    Catch,
    Throw,

    Dot,
    Equal,
    Plus,
    Minus,
    Star,
    Slash,
    BackSlash,
    Percent,
    StarStar,
    EqualEqual,
    Bang,
    BangEqual,
    Less,
    Greater,
    LessEqual,
    GreaterEqual,
    PlusEqual,
    MinusEqual,
    StarEqual,
    SlashEqual,
    BackSlashEqual,
    PercentEqual,
    StarStarEqual,
    QuestionQuestion,

    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Comma,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub line: usize,
    pub col: usize,
}
